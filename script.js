let currentPool = imagePool;
let randomImages = [];

function generateRandomImages(containerId, count, pool = imagePool) {
  const container = document.getElementById(containerId);
  if (!container) return;

  container.innerHTML = '';

  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  const amount = Math.min(count, shuffled.length);

  for (let i = 0; i < amount; i++) {
    const img = document.createElement('img');
    img.src = shuffled[i];
    img.classList.add('random-img');

    const randomTop = Math.floor(Math.random() * 90);
    const randomLeft = Math.floor(Math.random() * 85);
    const randomRotate = Math.floor(Math.random() * 50) - 25;

    const parallaxSpeed = (Math.random() * 0.8) - 0.2;
    img.dataset.speed = parallaxSpeed;

    img.style.top = `${randomTop}%`;
    img.style.left = `${randomLeft}%`;
    img.style.rotate = `${randomRotate}deg`;

    container.appendChild(img);
  }
}

window.addEventListener('DOMContentLoaded', () => {
  generateRandomImages('side-left', 300, currentPool);
  generateRandomImages('side-right', 300, currentPool);
  randomImages = Array.from(document.querySelectorAll('.random-img'));
});


function updateScrollEffects() {
  const scrollTop = window.scrollY;

  randomImages.forEach(img => {
    const speed = parseFloat(img.dataset.speed) || 0;
    img.style.transform = `translateY(${scrollTop * speed}px)`;
  });
}

let scrollTicking = false;
window.addEventListener('scroll', () => {
  if (scrollTicking) return;
  scrollTicking = true;
  requestAnimationFrame(() => {
    updateScrollEffects();
    scrollTicking = false;
  });
});